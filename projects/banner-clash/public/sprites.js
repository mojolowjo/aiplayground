// Turn a half-grid into full rows.
function expand(rows) { return rows.map(r => r + r.slice(0, -1).split('').reverse().join('')); }

const cache = new Map();
// A sprite as a canvas, `scale` screen pixels per art pixel, with a 1-pixel outline in the team colour.
export function sprite(id, team = null, scale = 1) {
  const key = id + '|' + team + '|' + scale;
  if (cache.has(key)) return cache.get(key);
  const def = SPRITES[id] || SPRITES.imps, rows = expand(def.rows);
  const h = rows.length, w = Math.max(...rows.map(r => r.length));
  const c = document.createElement('canvas'); c.width = (w + 2) * scale; c.height = (h + 2) * scale;
  const g = c.getContext('2d');
  const at = (x, y) => (rows[y] && rows[y][x] && rows[y][x] !== '.') ? rows[y][x] : null;
  if (team) {
    g.fillStyle = team;
    for (let y = -1; y <= h; y++) for (let x = -1; x <= w; x++) {
      if (at(x, y)) continue;
      if (at(x - 1, y) || at(x + 1, y) || at(x, y - 1) || at(x, y + 1)) g.fillRect((x + 1) * scale, (y + 1) * scale, scale, scale);
    }
  }
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const ch = at(x, y); if (!ch) continue;
    g.fillStyle = def.pal[ch] || P[ch] || '#ff00ff';
    g.fillRect((x + 1) * scale, (y + 1) * scale, scale, scale);
  }
  cache.set(key, c);
  return c;
}
export const spriteURL = (id, scale = 4) => sprite(id, null, scale).toDataURL();
